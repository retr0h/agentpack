// Package build orchestrates the agentpack build pipeline.
//
// Usage:
//
//	vfs := osfs.NewWithNoIdm()
//	b := build.New()
//	results, err := b.Run(ctx, vfs, build.Options{
//	    Dir:   "/path/to/repo",        // must be a git repo
//	    Names: []string{"my-skill"},   // empty = all plugins
//	})
//
// Build reads agentpack.yaml from Dir, resolves each plugin's file entries,
// captures git metadata, computes SHA256 checksums, and writes a
// {name}-{version}.agentpack archive to Dir. The working directory must be a
// git repository so that commit SHA and branch are captured.
package build

import (
	"context"
	"encoding/json"
	"fmt"
	"path"
	"path/filepath"
	"runtime"
	"time"

	"github.com/avfs/avfs"
	"gopkg.in/yaml.v3"

	"github.com/retr0h/agentpack/internal/archive"
	"github.com/retr0h/agentpack/internal/checksum"
	"github.com/retr0h/agentpack/internal/manifest"
	"github.com/retr0h/agentpack/internal/metadata"
)

// Builder orchestrates the agentpack build pipeline.
type Builder struct{}

// New returns a new Builder ready to run build pipelines.
func New() *Builder { return &Builder{} }

// Options configures a build run.
type Options struct {
	Dir   string   // working directory (must be a git repo)
	Names []string // plugin names to build (empty = all)
}

// Result holds the outcome of building a single plugin.
type Result struct {
	Name        string
	Version     string
	ArchivePath string
	SHA256      string
	FileCount   int
	Size        int64
}

// Run executes the build pipeline for all selected plugins.
func (b *Builder) Run(ctx context.Context, vfs avfs.VFS, opts Options) ([]Result, error) {
	m, err := manifest.Load(ctx, vfs, opts.Dir)
	if err != nil {
		return nil, err
	}

	plugins := manifest.Normalize(m)

	if len(opts.Names) > 0 {
		plugins, err = filterPlugins(plugins, opts.Names)
		if err != nil {
			return nil, err
		}
	}

	meta, err := metadata.Capture(ctx, opts.Dir, "", "")
	if err != nil {
		meta = &metadata.Metadata{
			BuildTimestamp: time.Now().UTC().Format(time.RFC3339),
			BuilderVersion: "dev",
			Platform:       runtime.GOOS + "-" + runtime.GOARCH,
		}
	}

	var results []Result

	for _, p := range plugins {
		if err := ctx.Err(); err != nil {
			return nil, err
		}

		r, err := buildPlugin(ctx, vfs, opts.Dir, p, meta)
		if err != nil {
			return nil, fmt.Errorf("plugin %q: %w", p.Name, err)
		}

		results = append(results, r)
	}

	return results, nil
}

func filterPlugins(plugins []manifest.Plugin, names []string) ([]manifest.Plugin, error) {
	idx := make(map[string]manifest.Plugin, len(plugins))
	for _, p := range plugins {
		idx[p.Name] = p
	}

	result := make([]manifest.Plugin, 0, len(names))

	for _, n := range names {
		p, ok := idx[n]
		if !ok {
			return nil, fmt.Errorf("plugin %q not found in agentpack.yaml", n)
		}

		result = append(result, p)
	}

	return result, nil
}

// buildPlugin produces a single .agentpack archive in the generic format:
//
//	.agentpack/
//	  agentpack.yaml    (serialised plugin manifest)
//	  metadata.json     (build metadata)
//	  checksums.txt     (SHA256 of every file in the archive)
//	skills/
//	  *.md
//	commands/
//	  *.md
//	hooks/
//	  ...
//	agents/
//	  ...
//	mcp/
//	  ...
//	settings/
//	  ...
//
// No marketplaces/ prefix and no .claude-plugin/ descriptors are written here;
// those are generated by each target driver at install time.
func buildPlugin(
	ctx context.Context,
	vfs avfs.VFS,
	dir string,
	p manifest.Plugin,
	meta *metadata.Metadata,
) (Result, error) {
	meta.Name = p.Name
	meta.Version = p.Version

	var files []archive.FileEntry

	type section struct {
		label   string
		entries []manifest.Entry
	}

	sections := []section{
		{"skills", p.Skills},
		{"commands", p.Commands},
		{"hooks", p.Hooks},
		{"agents", p.Agents},
		{"settings", p.Settings},
	}

	for _, s := range sections {
		if len(s.entries) == 0 {
			continue
		}

		pairs, err := manifest.ResolveEntries(ctx, vfs, dir, s.entries)
		if err != nil {
			return Result{}, fmt.Errorf("%s: %w", s.label, err)
		}

		for _, fp := range pairs {
			files = append(files, archive.FileEntry{
				Src:         fp.Src,
				ArchivePath: path.Join(s.label, fp.Dest),
			})
		}
	}

	mcpFiles, err := buildMCPEntries(ctx, vfs, dir, p)
	if err != nil {
		return Result{}, err
	}

	files = append(files, mcpFiles...)

	metaJSON, err := json.MarshalIndent(meta, "", "  ")
	if err != nil {
		return Result{}, fmt.Errorf("marshaling metadata: %w", err)
	}

	files = append(files, archive.FileEntry{
		ArchivePath: ".agentpack/metadata.json",
		Content:     metaJSON,
	})

	manifestYAML, err := yaml.Marshal(p)
	if err != nil {
		return Result{}, fmt.Errorf("marshaling agentpack.yaml: %w", err)
	}

	files = append(files, archive.FileEntry{
		ArchivePath: ".agentpack/agentpack.yaml",
		Content:     manifestYAML,
	})

	checksumEntries, err := computeArchiveChecksums(ctx, vfs, files)
	if err != nil {
		return Result{}, err
	}

	checksumContent := formatChecksums(checksumEntries)
	files = append(files, archive.FileEntry{
		ArchivePath: ".agentpack/checksums.txt",
		Content:     checksumContent,
	})

	outputName := fmt.Sprintf("%s-%s.agentpack", p.Name, p.Version)
	outputPath := filepath.Join(dir, outputName)

	if err := archive.Create(ctx, vfs, outputPath, files); err != nil {
		return Result{}, fmt.Errorf("creating archive: %w", err)
	}

	info, err := vfs.Stat(outputPath)
	if err != nil {
		return Result{}, fmt.Errorf("stat archive: %w", err)
	}

	archiveHash, err := checksum.ComputeFile(ctx, vfs, outputPath)
	if err != nil {
		return Result{}, fmt.Errorf("hashing archive: %w", err)
	}

	return Result{
		Name:        p.Name,
		Version:     p.Version,
		ArchivePath: outputPath,
		SHA256:      archiveHash,
		FileCount:   len(checksumEntries),
		Size:        info.Size(),
	}, nil
}

func buildMCPEntries(
	ctx context.Context,
	vfs avfs.VFS,
	dir string,
	p manifest.Plugin,
) ([]archive.FileEntry, error) {
	if len(p.MCP) == 0 {
		return nil, nil
	}

	var files []archive.FileEntry

	for _, mcp := range p.MCP {
		if err := ctx.Err(); err != nil {
			return nil, err
		}

		if mcp.Config != "" {
			srcPath := filepath.Join(dir, mcp.Config)
			if _, err := vfs.Stat(srcPath); err != nil {
				if avfs.IsNotExist(err) {
					return nil, fmt.Errorf("mcp config not found: %s", mcp.Config)
				}

				return nil, fmt.Errorf("stat mcp config: %w", err)
			}

			files = append(files, archive.FileEntry{
				Src:         srcPath,
				ArchivePath: "mcp/.mcp.json",
			})
		}
	}

	return files, nil
}

func computeArchiveChecksums(
	ctx context.Context,
	vfs avfs.VFS,
	files []archive.FileEntry,
) ([]checksum.Entry, error) {
	var entries []checksum.Entry

	for _, f := range files {
		if err := ctx.Err(); err != nil {
			return nil, err
		}

		var hash string

		if f.Src != "" {
			var err error

			hash, err = checksum.ComputeFile(ctx, vfs, f.Src)
			if err != nil {
				return nil, fmt.Errorf("checksum %s: %w", f.Src, err)
			}
		} else {
			hash = checksum.ComputeBytes(f.Content)
		}

		entries = append(entries, checksum.Entry{
			Hash: hash,
			Path: f.ArchivePath,
		})
	}

	return entries, nil
}

func formatChecksums(entries []checksum.Entry) []byte {
	var buf []byte

	for _, e := range entries {
		buf = fmt.Appendf(buf, "%s  %s\n", e.Hash, e.Path)
	}

	return buf
}
